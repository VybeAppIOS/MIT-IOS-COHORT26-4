#!/usr/bin/env python3
"""Writes VybeKit/Sources/Design/Theme/ColorFallbacks.swift from Design/Resources/Colors.xcassets.

Why: an asset catalog built by a newer Xcode can be unreadable on an older iOS (seen on an iPhone running iOS 26.6.1
with Xcode 27.1: every colour came back empty, so the app looked blank). Theme.Color reads the catalog first and only
uses these copies if the catalog fails. The catalog stays the only place where colours are edited: run this script
after changing a colour (`--check` fails if the generated file is out of date).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "VybeKit/Sources/Design/Resources/Colors.xcassets")
OUT = os.path.join(ROOT, "VybeKit/Sources/Design/Theme/ColorFallbacks.swift")


def components(entry):
    c = entry["color"]["components"]
    return tuple(float(c[k]) for k in ("red", "green", "blue", "alpha"))


def render():
    lines = []
    for name in sorted(os.listdir(ASSETS)):
        if not name.endswith(".colorset"):
            continue
        data = json.load(open(os.path.join(ASSETS, name, "Contents.json")))
        light, dark = None, None
        for entry in data["colors"]:
            if any(a.get("value") == "dark" for a in entry.get("appearances", [])):
                dark = components(entry)
            elif "appearances" not in entry:
                light = components(entry)
        dark = dark or light
        fmt = lambda t: "[" + ", ".join(f"{v:.3f}" for v in t) + "]"
        lines.append(f'        "{name[:-9]}": ColorPair(light: {fmt(light)}, dark: {fmt(dark)}),')
    body = ",\n".join(line.rstrip(",") for line in lines)
    return f'''import Foundation

// Generated by scripts/gen_color_fallbacks.py from Resources/Colors.xcassets. Do not edit by hand: change the colour in
// the asset catalog and run the script. Used only when the catalog cannot be read (see Theme.Color).

/// Red, green, blue and alpha from 0 to 1, for the light and the dark appearance.
struct ColorPair: Sendable {{
    let light: [Double]
    let dark: [Double]
}}

enum ColorFallbacks {{
    static let pairs: [String: ColorPair] = [
{body}
    ]
}}
'''


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("ColorFallbacks.swift is out of date: run python3 scripts/gen_color_fallbacks.py")
            sys.exit(1)
        print("ColorFallbacks.swift is up to date")
    else:
        open(OUT, "w").write(text)
        print("Wrote", os.path.relpath(OUT, ROOT))
